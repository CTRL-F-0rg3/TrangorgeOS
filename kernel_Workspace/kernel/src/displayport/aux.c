void dp_aux_sink_init(void)
{
    for (uint32_t i = 0; i < 0x400; i++) {
        dpcd[i] = 0;
    }

    dpcd[DPCD_REV] = 0x12;
    dpcd[DPCD_MAX_LINK_RATE] = 0x14;
    dpcd[DPCD_MAX_LANE_COUNT] = 0x04;

    train_step = 0;
}

bool dp_aux_read(uint32_t addr, void *buf, uint32_t len)
{
    if (addr + len > 0x400) {
        return false;
    }

    uint8_t *out = (uint8_t *)buf;

    for (uint32_t i = 0; i < len; i++) {
        out[i] = dpcd[addr + i];
    }

    return true;
}

bool dp_aux_write(uint32_t addr, const void *buf, uint32_t len)
{
    if (addr + len > 0x400) {
        return false;
    }

    const uint8_t *in = (const uint8_t *)buf;

    for (uint32_t i = 0; i < len; i++) {
        dpcd[addr + i] = in[i];
    }

    if (addr <= DPCD_TRAINING_SET &&
        DPCD_TRAINING_SET < addr + len) {
        uint8_t pat = dpcd[DPCD_TRAINING_SET] & 0x03;

        if (pat == 1) {
            dpcd[DPCD_LANE_STATUS] = 0x11;
            dpcd[DPCD_LANE_STATUS + 1] = 0x11;
        } else if (pat == 2) {
            train_step++;

            if (train_step >= 2) {
                dpcd[DPCD_LANE_STATUS] = 0x77;
                dpcd[DPCD_LANE_STATUS + 1] = 0x77;
                dpcd[DPCD_SYMBOL_LOCK] = 0x01;
            }
        } else {
            train_step = 0;
        }
    }

    return true;
}

bool dp_aux_read_edid(void *buf, uint32_t len)
{
    if (len > 128) {
        len = 128;
    }

    uint8_t *out = (uint8_t *)buf;

    for (uint32_t i = 0; i < len; i++) {
        out[i] = EDID[i];
    }

    return true;
}
